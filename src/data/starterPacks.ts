export function createDeckFromPack(pack: StarterPack): FeudDeck {
  return {
    id: `deck-${Date.now()}`,
    showTitle: pack.showTitle,
    subtitle: pack.title,
    teamOneName: pack.teamOneDefault,
    teamTwoName: pack.teamTwoDefault,
    themeId: pack.recommendedTheme,
    exportMode: 'host_and_board',
    includeRulesSlide: true,
    includeFastMoney: true,
    rounds: pack.rounds.map((r, idx) => ({
      ...r,
      id: `round-${Date.now()}-${idx}`,
      answers: r.answers.map((a, aIdx) => ({
        ...a,
        id: `ans-${Date.now()}-${idx}-${aIdx}`,
      })),
    })),
    fastMoneyQuestions: pack.fastMoneyQuestions.map((q, qIdx) => ({
      ...q,
      id: `fm-${Date.now()}-${qIdx}`,
    })),
  };
}
